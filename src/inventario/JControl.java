    private void jBoxCategoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBoxCategoriaActionPerformed
        // TODO add your handling code here:
//        Mostramos los botones de acuerdo a la categoria
        String opcion = (String) jBoxCategoria.getSelectedItem();
        switch (opcion) {
            case "Electrodomesticos":
                jLabelTitle1.setText("Modelo");
                jLabelTitle2.setText("Marca");
                jLabelTitle2.setVisible(true);
                jInputTitle2.setVisible(true);
                break;
            case "Ropa":
                jLabelTitle1.setText("Material");
                jLabelTitle2.setText("Talla");
                jLabelTitle2.setVisible(true);
                jInputTitle2.setVisible(true);
                break;
            case "Libros":
                jLabelTitle1.setText("Autor");
                jLabelTitle2.setVisible(false);
                jInputTitle2.setVisible(false);
                break;
            case "Deportes":
                jLabelTitle1.setText("Disciplina");
                jLabelTitle2.setVisible(false);
                jInputTitle2.setVisible(false);
        }
    }//GEN-LAST:event_jBoxCategoriaActionPerformed

