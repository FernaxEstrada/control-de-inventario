    private void jButtonResolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonResolverActionPerformed
        // TODO add your handling code here:
        String nombre = jInputNombre.getText();
        String descripcion = jInputDescripcion.getText();
        double precio = Double.parseDouble(jInputPrecio.getText());
        int descuento = Integer.parseInt(jInputDescuento.getText());
        int stock = Integer.parseInt(jInputStock.getText());
        String opcion = (String) jBoxCategoria.getSelectedItem();
        Object nuevo = new Object();
        switch (opcion) {
            case "Electrodomesticos":
                String text1 = jInputTitle1.getText();
                String text2 = jInputTitle2.getText();
                Electrodomesticos x1 = new Electrodomesticos(nombre, descripcion, precio, descuento, stock, opcion, text1, text2);
                nuevo = x1;
                break;
            case "Ropa":
                String text3 = jInputTitle1.getText();
                String text4 = jInputTitle2.getText();
                Ropa x2 = new Ropa(nombre, descripcion, precio, descuento, stock, opcion, text3, text4);
                nuevo = x2;
                break;
            case "Libros":
                String text5 = jInputTitle1.getText();
                Libro x3 = new Libro(nombre, descripcion, precio, descuento, stock, opcion, text5);
                nuevo = x3;
                break;
            case "Deportes":
                String text6 = jInputTitle1.getText();
                Deporte x4 = new Deporte(nombre, descripcion, precio, descuento, stock, opcion, text6);
                nuevo = x4;
                break;
        }
        Inv.registrar((Producto) nuevo);
        jLabelMonto.setText(Double.toString(Inv.CalcularPrecioTotal()));
        jLabelMontoConDesc.setText(Double.toString(Inv.CalcularPrecioTotalDes()));
    }//GEN-LAST:event_jButtonResolverActionPerformed

